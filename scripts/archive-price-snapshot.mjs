import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SNAPSHOT_PATH = path.join(ROOT, 'price-snapshot.js');
const HISTORY_PATH = path.join(ROOT, 'price-history.js');

async function loadWindowFile(file) {
  const source = await fs.readFile(file, 'utf8');
  const sandbox = { window: {} };
  vm.runInNewContext(source, sandbox, { filename: path.basename(file) });
  return sandbox.window;
}

async function main() {
  const snapshotWindow = await loadWindowFile(SNAPSHOT_PATH);
  const historyWindow = await loadWindowFile(HISTORY_PATH);
  const snapshot = snapshotWindow.FL_PRICE_SNAPSHOT || {};
  const history = historyWindow.FL_PRICE_HISTORY || { version: 1, marketplace: snapshot.marketplace, snapshots: [] };
  const offerEntries = Object.entries(snapshot.offers || {}).filter(([, offer]) => Number.isFinite(offer.price));

  if (!snapshot.generatedAt || !offerEntries.length) {
    console.log('No generated live-price snapshot; monthly history unchanged.');
    return;
  }

  const month = snapshot.generatedAt.slice(0, 7);
  const monthlySnapshot = {
    month,
    generatedAt: snapshot.generatedAt,
    offerCount: offerEntries.length,
    offers: Object.fromEntries(offerEntries.map(([id, offer]) => [id, {
      asin: offer.asin,
      price: offer.price,
      currency: offer.currency || 'USD',
      availability: offer.availability,
      checkedAt: offer.checkedAt
    }]))
  };
  const snapshots = Array.isArray(history.snapshots) ? history.snapshots.filter((entry) => entry.month !== month) : [];
  snapshots.push(monthlySnapshot);
  snapshots.sort((a, b) => a.month.localeCompare(b.month));

  const output = {
    version: 1,
    marketplace: snapshot.marketplace || history.marketplace || 'www.amazon.com',
    snapshots
  };
  await fs.writeFile(HISTORY_PATH, `/* Monthly Amazon Creators API snapshots. Generated by scripts/archive-price-snapshot.mjs. */\nwindow.FL_PRICE_HISTORY = ${JSON.stringify(output, null, 2)};\n`, 'utf8');
  console.log(`Archived ${offerEntries.length} offers for ${month}.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
